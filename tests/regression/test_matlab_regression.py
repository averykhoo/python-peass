"""
PEASS Test Suite - Legacy Matlab Regression Tests
File path: tests/regression/test_matlab_regression.py
"""

import numpy as np
import pytest
import soundfile as sf

from peass import DecompositionConfiguration
from peass import decompose_distortion_components


@pytest.mark.regression
def test_regression_against_matlab_references(matlab_ref_resources):
    """
    Validates Python-decomposed waveforms directly against the original
    reference WAV files generated by the official MATLAB PEASS v2.0.1 toolbox.
    """
    # 1. Load Inputs
    target_src, fs = sf.read(matlab_ref_resources / "targetSrc.wav")
    interf1, _ = sf.read(matlab_ref_resources / "interfSrc1.wav")
    interf2, _ = sf.read(matlab_ref_resources / "interfSrc2.wav")
    estimate, _ = sf.read(matlab_ref_resources / "targetEstimate.wav")

    # 2. Decompose using Python port
    config = DecompositionConfiguration(shade_in_milliseconds=10.0, shade_out_milliseconds=10.0)
    result = decompose_distortion_components(
        source_files=[target_src, interf1, interf2],
        estimate_file=estimate,
        configuration=config,
        sampling_frequency_hz=float(fs)
    )
    py_waveforms = result.waveforms

    # 3. Define components to verify against MATLAB gold standard files
    validation_map = [
        (py_waveforms.true_target, "targetEstimate_true.wav", "true_target"),
        (py_waveforms.target_distortion, "targetEstimate_eTarget.wav", "target_distortion"),
        (py_waveforms.interference, "targetEstimate_eInterf.wav", "interference"),
        (py_waveforms.artifacts, "targetEstimate_eArtif.wav", "artifacts")
    ]

    for py_val, gold_filename, label in validation_map:
        gold_val, _ = sf.read(matlab_ref_resources / gold_filename)

        # Sync lengths (handling decimation alignment limits)
        min_len = min(len(py_val), len(gold_val))
        py_segment = py_val[:min_len]
        gold_segment = gold_val[:min_len]

        for ch in range(py_segment.shape[1]):
            # If the segment is silent, correlation is NaN; check variance instead
            if np.std(gold_segment[:, ch]) < 1e-4:
                assert np.std(py_segment[:, ch]) < 1e-4, f"Energy mismatch in {label} channel {ch}"
            else:
                corr = np.corrcoef(py_segment[:, ch], gold_segment[:, ch])[0, 1]
                assert corr > 0.95, f"Regression failure: {label} (CH{ch}) correlation is {corr:.4f}"
