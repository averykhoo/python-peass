def cellA12_cellB_vecC_2_cellB_vecCA21(x):
    # format conversion
    # x is an A1-by-A2 list of lists, each entry a B1-long list of 1-D subband
    # vectors (MATLAB's cell{a1,a2}{b1,b2}). MATLAB's second cell dimension B2
    # is always 1 here, so it is dropped rather than carried as a length-1 axis.
    A1 = len(x)
    A2 = len(x[0])
    B1 = len(x[0][0])  # MATLAB [B1 B2] = size(x{1,1}), B2 == 1
    C = [len(v) for v in x[0][0]]  # MATLAB cellfun('length',x{1,1})

    dtype = np.asarray(x[0][0][0]).dtype
    # MATLAB arrayfun(@(n)zeros(n,A2,A1),C,...)
    y = [np.zeros((n, A2, A1), dtype=dtype) for n in C]
    for a1 in range(1, A1 + 1):  # MATLAB a1=1:A1
        for a2 in range(1, A2 + 1):  # MATLAB a2=1:A2
            for b1 in range(1, B1 + 1):  # MATLAB b1=1:B1
                # MATLAB y{b1,b2}(:,a2,a1) = x{a1,a2}{b1,b2}
                y[b1 - 1][:, a2 - 1, a1 - 1] = np.asarray(x[a1 - 1][a2 - 1][b1 - 1])

    return y


# >>> MATLAB
# %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
# function x = cellB_vecCA21_2_cellA12_cellB_vecC(y)
# % format conversion
#
# [B1 B2]= size(y);
# [dum A2 A1] = size(y{1,1});
#
# x = cell(A1,A2);
# for a1=1:A1
#     for a2=1:A2
#         x{a1,a2} = cell(B1,B2);
#         for b1=1:B1
#             for b2=1:B2
#                 x{a1,a2}{b1,b2} = squeeze(y{b1,b2}(:,a2,a1)).';
#             end
#         end
#     end
# end
#
# return
#
# <<< MATLAB


def cellB_vecCA21_2_cellA12_cellB_vecC(y):
    # format conversion
    B1 = len(y)  # MATLAB [B1 B2] = size(y), B2 == 1
    # MATLAB [dum A2 A1] = size(y{1,1}): with NEst == 1 MATLAB drops the
    # trailing singleton and fills A1 with 1, which is what shape[2] gives here.
    A2 = y[0].shape[1]
    A1 = y[0].shape[2]

    x = [[None] * A2 for _ in range(A1)]  # MATLAB cell(A1,A2)
    for a1 in range(1, A1 + 1):  # MATLAB a1=1:A1
        for a2 in range(1, A2 + 1):  # MATLAB a2=1:A2
            x[a1 - 1][a2 - 1] = [None] * B1  # MATLAB cell(B1,B2)
            for b1 in range(1, B1 + 1):  # MATLAB b1=1:B1
                # MATLAB squeeze(y{b1,b2}(:,a2,a1)).' -> a row vector
                x[a1 - 1][a2 - 1][b1 - 1] = y[b1 - 1][:, a2 - 1, a1 - 1]

    return x


