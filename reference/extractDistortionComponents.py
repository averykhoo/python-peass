def _as_audio_matrix(signal):
    """`audioread` always returns nSamples-by-nChannels, even for mono."""
    a = np.asarray(signal, dtype=float)
    if a.ndim == 1:
        return a.reshape(-1, 1)
    return a


def audioread(filename):
    """MATLAB `[y, fs] = audioread(file)` for PCM-16 wav files.

    MATLAB normalizes 16-bit integer samples by 32768 onto [-1, 1).
    """
    fs, data = scipy.io.wavfile.read(filename)
    if data.dtype == np.int16:
        data = data.astype(float) / 32768.0
    else:
        data = data.astype(float)
    return _as_audio_matrix(data), float(fs)


# !!! DEVIATION: MATLAB's exact float-to-int16 rule for `audiowrite` is not
# documented and could not be verified here, so `round(y*32768)` clipped to the
# int16 range is used -- the convention the older `wavwrite` used. Any
# disagreement is at most one LSB (~3e-5 of full scale), and it affects only
# this file wrapper: the array API, which is what the tests and every caller
# use, never quantizes at all.
def audiowrite(filename, y, fs):
    """MATLAB `audiowrite(file, y, fs)`, 16-bit PCM."""
    scaled = np.clip(matlab_round(np.asarray(y) * 32768.0), -32768, 32767)
    scipy.io.wavfile.write(filename, int(fs), scaled.astype(np.int16))


def extractDistortionComponents_files(srcFiles, estFile, options=None, verbose=False):
    """MATLAB's own entry point: filenames in, filenames out."""
    srcSignals = []
    fs = None
    for srcFile in srcFiles:
        signal, fs = audioread(srcFile)
        srcSignals.append(signal)
    estSignal, fs = audioread(estFile)

    trueSynth, targetSynth, interfSynth, artifSynth, outputFilenames = \
        extractDistortionComponents(srcSignals, estSignal, fs, options,
                                    estFile=estFile, verbose=verbose)

    audiowrite(outputFilenames[0], trueSynth, fs)
    audiowrite(outputFilenames[1], targetSynth, fs)
    audiowrite(outputFilenames[2], interfSynth, fs)
    audiowrite(outputFilenames[3], artifSynth, fs)
    return outputFilenames
