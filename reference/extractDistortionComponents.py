"""Decomposition of an estimated source into true / target / interference / artifact.

Transcribed from MATLAB PEASS v2.0.1.

The primary API, `extractDistortionComponents`, takes and returns arrays; the
MATLAB entry point reads and writes `.wav` files, and that is provided as the
thin wrapper `extractDistortionComponents_files`.
"""
